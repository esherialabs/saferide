export type MessageKey = keyof typeof en;
export type Messages = Record<MessageKey, string>;
export type Locale = 'en';

const dictionaries: Record<Locale, Messages> = { en };

let locale: Locale = 'en';

export function setLocale(next: Locale): void {
  locale = next;
}

export function currentLocale(): Locale {
  return locale;
}

export type MessageVars = Record<string, string | number>;

export function t(key: MessageKey, vars?: MessageVars): string {
  const template = dictionaries[locale][key] ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Hook form so components can switch to context-based locales later without changing call sites. */
export function useT(): typeof t {
  return t;
}

// --- formatting ---------------------------------------------------------------

// HURIA works in Mombasa; all times show in East Africa Time.
const TIME_ZONE = 'Africa/Nairobi';

export function formatDateTime(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return '';
  const text = new Intl.DateTimeFormat('en-GB', {
    day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', timeZone: TIME_ZONE,
  }).format(date);
  return `${text} EAT`;
}

export function formatDate(iso: string): string {
  const date = new Date(`${iso}T12:00:00Z`);
  if (Number.isNaN(date.getTime())) return iso;
  return new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(date);
}

export function formatTime(epochMs: number): string {
  return `${new Intl.DateTimeFormat('en-GB', { hour: '2-digit', minute: '2-digit', timeZone: TIME_ZONE }).format(new Date(epochMs))} EAT`;
}

export function formatDuration(ms: number): string {
  const total = Math.max(0, Math.ceil(ms / 1000));
  const minutes = Math.floor(total / 60);
  const seconds = total % 60;
  return minutes > 0 ? t('time.minutesSeconds', { minutes, seconds }) : t('time.seconds', { seconds });
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
